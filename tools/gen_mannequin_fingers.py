"""Generates MannequinFingers.cs: the UE5 mannequin's finger bones relative to their parents.

Input is the same kind of reference-pose dump gen_mannequin_data.py reads (manny_bones.json, world
space, from AnimPoseExtensions in the Unreal Editor; tools/manny_bones.json has every bone of
SK_Mannequin). Each finger bone is stored as its offset and rotation in its parent's frame, so the
generator can hang Manny's fingers off its own (T-posed) hand with Manny's bone orientations, which
is what the mannequin's animations expect.

Unreal space is left-handed; converted as in gen_mannequin_data.py: y -> -y, (x, y, z, w) -> (-x, y, -z, w).

usage: python gen_mannequin_fingers.py manny_bones.json ../src/LowPolyCharGen.Core/MannequinFingers.cs
"""
import json
import sys

import numpy as np

FINGERS = [("thumb_01_l", "hand_l"), ("thumb_02_l", "thumb_01_l"), ("thumb_03_l", "thumb_02_l")]
for f in ("index", "middle", "ring", "pinky"):
    FINGERS += [(f"{f}_metacarpal_l", "hand_l"), (f"{f}_01_l", f"{f}_metacarpal_l"),
                (f"{f}_02_l", f"{f}_01_l"), (f"{f}_03_l", f"{f}_02_l")]


def convert(b):
    x, y, z = b["world"]["t"]
    qx, qy, qz, qw = b["world"]["q"]
    return np.array([x, -y, z]), np.array([-qx, qy, -qz, qw])


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return np.array([aw * bx + ax * bw + ay * bz - az * by,
                     aw * by - ax * bz + ay * bw + az * bx,
                     aw * bz + ax * by - ay * bx + az * bw,
                     aw * bw - ax * bx - ay * by - az * bz])


def qinv(q):
    return np.array([-q[0], -q[1], -q[2], q[3]]) / np.dot(q, q)


def rotate(q, v):
    p = np.array([v[0], v[1], v[2], 0.0])
    return qmul(qmul(q, p), qinv(q))[:3]


def main():
    data = {b["name"]: b for b in json.load(open(sys.argv[1]))}
    lines = []
    for name, parent in FINGERS:
        t, q = convert(data[name])
        pt, pq = convert(data[parent])
        # System.Numerics composes child world = local * parent (row vectors): local = child * inverse(parent).
        local_q = qmul(qinv(pq), q)
        local_q /= np.linalg.norm(local_q)
        if local_q[3] < 0:
            local_q = -local_q
        local_t = rotate(qinv(pq), t - pt)
        lines.append(f'        new("{name}", "{parent}", new Vector3({local_t[0]:.4f}f, {local_t[1]:.4f}f, {local_t[2]:.4f}f), '
                     f'new Quaternion({local_q[0]:.6f}f, {local_q[1]:.6f}f, {local_q[2]:.6f}f, {local_q[3]:.6f}f)),')
    body = "\n".join(lines)
    src = f"""// Generated by tools/gen_mannequin_fingers.py from tools/manny_bones.json - do not edit.
using System.Numerics;

namespace LowPolyCharGen;

/// <summary>The UE5 mannequin's left finger bones: offset and rotation in the parent bone's frame.</summary>
internal static class MannequinFingers
{{
    public readonly record struct Entry(string Name, string Parent, Vector3 Offset, Quaternion Rotation);

    public static readonly Entry[] Bones =
    [
{body}
    ];
}}
"""
    open(sys.argv[2], "w", newline="\r\n").write(src)
    print(sys.argv[2], len(FINGERS), "bones")


if __name__ == "__main__":
    main()
